export const messages: Record<string, Dict> = { tr, en, es, zh, hi, ar, pt, ru, de, fr };

/** Yedek dil: bir anahtar çevrilmemişse buradan alınır. */
const FALLBACK = "en";

/**
 * Tarayıcı/sistem dilinden desteklenen bir kod seçer.
 * "tr-TR" → "tr", "zh-Hans-CN" → "zh". Eşleşme yoksa İngilizce.
 */
export function detectLocale(preferred?: readonly string[]): string {
  const list = preferred ?? (typeof navigator !== "undefined" ? navigator.languages : []) ?? [];
  for (const tag of list) {
    const base = tag.toLowerCase().split("-")[0];
    if (messages[base]) return base;
  }
  return FALLBACK;
}

export function isRtl(code: string): boolean {
  return LOCALES.find((l) => l.code === code)?.rtl ?? false;
}

/**
 * Bir dil için çeviri fonksiyonu üretir.
 *
 * `{ad}` biçimindeki yer tutucular `vars` ile doldurulur. Anahtar bulunamazsa
 * önce İngilizce'ye, o da yoksa anahtarın kendisine düşer — eksik çeviri
 * arayüzü boş bırakmamalı.
 */
export function translator(code: string) {
  const dict = messages[code] ?? messages[FALLBACK];
  return (key: string, vars?: Record<string, string | number>): string => {
    let text = dict[key] ?? messages[FALLBACK][key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        text = text.replaceAll(`{${k}}`, String(v));
      }
    }
    return text;
  };
}
